const ttsService = require('../services/ttsService');
const logger = require('../utils/logger');

/**
 * Get Available Voices from active backend provider
 */
const getVoices = async (req, res, next) => {
  try {
    const result = await ttsService.getVoices();
    res.status(200).json({
      success: true,
      ...result
    });
  } catch (err) {
    next(err);
  }
};

/**
 * Get active provider status
 */
const getStatus = async (req, res, next) => {
  try {
    const status = ttsService.getStatus();
    res.status(200).json({
      success: true,
      data: status
    });
  } catch (err) {
    next(err);
  }
};

/**
 * Synthesize speech
 */
const synthesizeSpeech = async (req, res, next) => {
  try {
    const params = req.sanitizedTTS;
    const result = await ttsService.synthesize(params);

    // If audio buffer was successfully generated by an external provider
    if (result.success && result.buffer) {
      res.setHeader('Content-Type', result.contentType || 'audio/mpeg');
      res.setHeader('Content-Length', result.buffer.length);
      res.setHeader(
        'Content-Disposition',
        `attachment; filename="${result.filename || 'generated-speech.mp3'}"`
      );
      return res.status(200).send(result.buffer);
    }

    // Honest handling if provider is browser mode or unconfigured
    const statusCode = result.code === 'BROWSER_TTS_MODE' ? 200 : 400;
    return res.status(statusCode).json({
      success: false,
      code: result.code || 'PROVIDER_UNAVAILABLE',
      message: result.message || 'Speech generation through backend provider is not configured.',
      browserSpeechSupported: true,
      recommendation: result.recommendation || 'Please use browser client-side speech synthesis.'
    });
  } catch (err) {
    next(err);
  }
};

module.exports = {
  getVoices,
  getStatus,
  synthesizeSpeech
};
